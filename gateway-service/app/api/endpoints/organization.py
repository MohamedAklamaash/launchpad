from enum import Enum
from uuid import UUID

from fastapi import APIRouter, Request
from pydantic import BaseModel, ConfigDict, Field

from app.core.config import settings
from app.services.proxy import proxy_request

router = APIRouter(prefix="/organizations", tags=["Organizations"])
invitation_router = APIRouter(prefix="/invitations", tags=["Organizations"])


class InvitableRole(str, Enum):
    admin = "admin"
    developer = "developer"
    viewer = "viewer"


class CreateInvitationBody(BaseModel):
    email: str = Field(max_length=254, example="teammate@example.com")
    role: InvitableRole = Field(description="Never owner: nobody can be invited as owner.")


class AcceptInvitationBody(BaseModel):
    token: str = Field(min_length=43, max_length=43, pattern=r"^[A-Za-z0-9_-]{43}$")


class OrganizationNameBody(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str = Field(min_length=1, max_length=200, description="Sanitized by auth-service.")


class ChangeMemberRoleBody(BaseModel):
    model_config = ConfigDict(extra="forbid")

    role: InvitableRole = Field(description="Never owner: ownership moves only by transfer.")


class TransferOwnershipBody(BaseModel):
    new_owner_account_id: UUID = Field(description="Account id of an active member to make owner.")


@router.get("", summary="List the caller's organizations",
            description="Behind ORGS_ENABLED (auth-service). Active memberships of the caller's "
                        "verified account only: id, name, role, is_personal.")
async def list_organizations(request: Request):
    return await proxy_request(f"{settings.AUTH_SERVICE_URL}/api/v1/organizations", request)


@router.post("", status_code=201, summary="Create a team organization",
             description="Behind ORGS_ENABLED (auth-service). The id is always generated by "
                         "the server; any body key other than `name` is rejected. The caller "
                         "becomes owner. Limited per account.")
async def create_organization(body: OrganizationNameBody, request: Request):
    return await proxy_request(f"{settings.AUTH_SERVICE_URL}/api/v1/organizations", request)


@router.patch("/{organization_id}", summary="Rename an organization",
              description="Owner or admin only, resolved by auth-service from the caller's "
                          "active Membership. Organizations cannot be deleted.")
async def rename_organization(organization_id: UUID, body: OrganizationNameBody, request: Request):
    return await proxy_request(
        f"{settings.AUTH_SERVICE_URL}/api/v1/organizations/{organization_id}", request)


@router.get("/{organization_id}/members", summary="List the organization's active members",
            description="Any active member. Viewers receive names and roles without emails.")
async def list_members(organization_id: UUID, request: Request):
    return await proxy_request(
        f"{settings.AUTH_SERVICE_URL}/api/v1/organizations/{organization_id}/members", request)


@router.patch("/{organization_id}/members/{account_id}", summary="Change a member's role",
              description="Owner or admin. The new role is admin, developer or viewer; the "
                          "owner's role cannot be changed here (use transfer-ownership).")
async def change_member_role(organization_id: UUID, account_id: UUID, body: ChangeMemberRoleBody,
                             request: Request):
    return await proxy_request(
        f"{settings.AUTH_SERVICE_URL}/api/v1/organizations/{organization_id}"
        f"/members/{account_id}", request)


@router.delete("/{organization_id}/members/{account_id}", status_code=204,
               summary="Remove a member, or leave the organization",
               description="Owner or admin may remove a non-owner member; any member may "
                           "remove themselves. The owner can neither be removed nor leave.")
async def remove_member(organization_id: UUID, account_id: UUID, request: Request):
    return await proxy_request(
        f"{settings.AUTH_SERVICE_URL}/api/v1/organizations/{organization_id}"
        f"/members/{account_id}", request)


@router.post("/{organization_id}/transfer-ownership",
             summary="Transfer the organization to another active member",
             description="Behind ORGS_ENABLED (auth-service). Current owner only, resolved by "
                         "auth-service from the caller's active owner Membership. Requires a "
                         "login within the exit-flow reauth window (401 reauth_required "
                         "otherwise). The caller becomes admin and their refresh tokens are "
                         "revoked. A personal organization cannot be transferred.")
async def transfer_ownership(organization_id: UUID, body: TransferOwnershipBody, request: Request):
    return await proxy_request(
        f"{settings.AUTH_SERVICE_URL}/api/v1/organizations/{organization_id}/transfer-ownership",
        request)


@router.post("/{organization_id}/invitations", status_code=201,
             summary="Invite an email address to an organization",
             description="Behind ORGS_ENABLED (auth-service). Owner or admin of the "
                         "organization only; the role is resolved by auth-service from the "
                         "caller's active Membership, never from the request. The "
                         "invitation token is emailed and never returned.")
async def create_invitation(organization_id: UUID, body: CreateInvitationBody, request: Request):
    return await proxy_request(
        f"{settings.AUTH_SERVICE_URL}/api/v1/organizations/{organization_id}/invitations", request)


@router.get("/{organization_id}/invitations",
            summary="List the organization's pending invitations")
async def list_invitations(organization_id: UUID, request: Request):
    return await proxy_request(
        f"{settings.AUTH_SERVICE_URL}/api/v1/organizations/{organization_id}/invitations", request)


@router.delete("/{organization_id}/invitations/{invitation_id}", status_code=204,
               summary="Revoke a pending invitation")
async def revoke_invitation(organization_id: UUID, invitation_id: UUID, request: Request):
    return await proxy_request(
        f"{settings.AUTH_SERVICE_URL}/api/v1/organizations/{organization_id}"
        f"/invitations/{invitation_id}", request)


@invitation_router.post("/accept", summary="Accept an organization invitation",
                        description="Requires the caller's session Authorization bearer token "
                                    "AND the invitation token in the body. The token is "
                                    "body-only so it never lands in URLs or access logs. The "
                                    "session's verified email must equal the invited email.")
async def accept_invitation(body: AcceptInvitationBody, request: Request):
    return await proxy_request(f"{settings.AUTH_SERVICE_URL}/api/v1/invitations/accept", request)
