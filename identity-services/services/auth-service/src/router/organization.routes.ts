import { Router } from 'express';
import { validateRequest } from '@launchpad/common';
import {
    AcceptInvitation,
    ChangeMemberRole,
    CreateInvitation,
    CreateOrganization,
    ListAuditEvents,
    ListInvitations,
    ListMembers,
    ListMyOrganizations,
    RemoveMember,
    RenameOrganization,
    RevokeInvitation,
    TransferOwnership,
} from '@/controllers/organization.controller';
import { auditQuerySchema } from '@/schemas/audit-event.schema';
import { requireOrgsEnabled } from '@/middleware/orgs-enabled.middleware';
import {
    acceptInvitationSchema,
    changeMemberRoleSchema,
    createInvitationSchema,
    orgInvitationParamsSchema,
    orgMemberParamsSchema,
    orgParamsSchema,
    organizationNameSchema,
    transferOwnershipSchema,
} from '@/schemas/organization.schema';

export const organizationRouter: Router = Router();
export const invitationRouter: Router = Router();

organizationRouter.use(requireOrgsEnabled);
invitationRouter.use(requireOrgsEnabled);

/**
 * @swagger
 * /api/v1/organizations:
 *   get:
 *     summary: List the caller's organizations
 *     description: >
 *       Behind ORGS_ENABLED. Only organizations where the caller's verified credential's
 *       account holds an ACTIVE membership. `is_personal` is true for a personal organization
 *       (including one the caller was invited into).
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     responses:
 *       200: { description: "[{ id, name, role, is_personal }]" }
 *       403: { description: Credential is not verified or not linked to the token's account }
 *   post:
 *     summary: Create a team organization
 *     description: >
 *       Behind ORGS_ENABLED. The id is generated by the server and cannot be supplied (a body
 *       with any key other than `name` is a 422). The caller becomes owner. Requires a
 *       verified credential whose Account is not shared with another credential row. The
 *       name is sanitized (NFKC, letters/digits/space and a few marks, 64 characters).
 *       Limited to 5 per account per hour; refused with 503 if the limiter is unavailable.
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required: [name]
 *             properties:
 *               name: { type: string, maxLength: 200 }
 *     responses:
 *       201: { description: "{ id, name, role: owner, is_personal: false }" }
 *       403: { description: Credential unverified or its Account is shared }
 *       422: { description: Invalid body or the name is empty after sanitizing }
 *       429: { description: Creation limit reached }
 *       503: { description: Rate limiter unavailable }
 */
organizationRouter.get('/', ListMyOrganizations);
organizationRouter.post('/', validateRequest({ body: organizationNameSchema }), CreateOrganization);

/**
 * @swagger
 * /api/v1/organizations/{id}:
 *   patch:
 *     summary: Rename an organization
 *     description: >
 *       Behind ORGS_ENABLED. Owner or admin only. Personal organizations may be renamed.
 *       Same name sanitizing as creation. Deleting an organization is not supported.
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     parameters:
 *       - { in: path, name: id, required: true, schema: { type: string, format: uuid } }
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required: [name]
 *             properties:
 *               name: { type: string, maxLength: 200 }
 *     responses:
 *       200: { description: "{ id, name }" }
 *       403: { description: Caller is a member but not an owner or admin }
 *       404: { description: Organization not found, or the caller is not an active member }
 */
organizationRouter.patch(
    '/:id',
    validateRequest({ params: orgParamsSchema, body: organizationNameSchema }),
    RenameOrganization,
);

/**
 * @swagger
 * /api/v1/organizations/{id}/members:
 *   get:
 *     summary: List the organization's active members
 *     description: >
 *       Behind ORGS_ENABLED. Any active member. Every row has an opaque membership `id`, a
 *       sanitized display name, role and joined_at. Viewers get nothing else; other roles also
 *       get `account_id` and `email`.
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     parameters:
 *       - { in: path, name: id, required: true, schema: { type: string, format: uuid } }
 *     responses:
 *       200: { description: "[{ id, account_id?, display_name, email?, role, joined_at }]" }
 *       404: { description: Organization not found, or the caller is not an active member }
 * /api/v1/organizations/{id}/members/{accountId}:
 *   patch:
 *     summary: Change a member's role
 *     description: >
 *       Behind ORGS_ENABLED. Owner or admin. The new role is admin, developer or viewer;
 *       `owner` is a 422, and an owner's own row is a 409. Ownership moves only through
 *       transfer-ownership.
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     parameters:
 *       - { in: path, name: id, required: true, schema: { type: string, format: uuid } }
 *       - { in: path, name: accountId, required: true, schema: { type: string, format: uuid } }
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required: [role]
 *             properties:
 *               role: { type: string, enum: [admin, developer, viewer] }
 *     responses:
 *       200: { description: Role changed }
 *       403: { description: Caller is a member but not an owner or admin }
 *       404: { description: Organization or target membership not found, or caller not a member }
 *       409: { description: Target is the owner }
 *   delete:
 *     summary: Remove a member, or leave the organization
 *     description: >
 *       Behind ORGS_ENABLED. Owner or admin may remove any non-owner member. Any active member
 *       may remove themselves (leave). The owner can neither be removed nor leave (409);
 *       transfer ownership first. Removal revokes the member's refresh tokens and pending
 *       invitations to their addresses.
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     parameters:
 *       - { in: path, name: id, required: true, schema: { type: string, format: uuid } }
 *       - { in: path, name: accountId, required: true, schema: { type: string, format: uuid } }
 *     responses:
 *       204: { description: Removed }
 *       403: { description: Caller is not an owner or admin and is not removing themselves }
 *       404: { description: Organization or target membership not found, or caller not a member }
 *       409: { description: Target is the owner }
 */
organizationRouter.get('/:id/members', validateRequest({ params: orgParamsSchema }), ListMembers);
organizationRouter.patch(
    '/:id/members/:accountId',
    validateRequest({ params: orgMemberParamsSchema, body: changeMemberRoleSchema }),
    ChangeMemberRole,
);
organizationRouter.delete(
    '/:id/members/:accountId',
    validateRequest({ params: orgMemberParamsSchema }),
    RemoveMember,
);

/**
 * @swagger
 * /api/v1/organizations/{id}/invitations:
 *   post:
 *     summary: Invite an email address to an organization
 *     description: >
 *       Behind ORGS_ENABLED. Caller must be an active owner or admin of the organization
 *       (resolved from the token's account, never the request). Role must be admin,
 *       developer or viewer. Rate limited per organization and per target email; refused
 *       with 503 if the limiter is unavailable. The invitation token is only ever sent by
 *       email and is never returned.
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     parameters:
 *       - { in: path, name: id, required: true, schema: { type: string, format: uuid } }
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required: [email, role]
 *             properties:
 *               email: { type: string, format: email }
 *               role: { type: string, enum: [admin, developer, viewer] }
 *     responses:
 *       201: { description: Invitation created and email queued }
 *       403: { description: Caller is a member but not an owner or admin }
 *       404: { description: Organization not found, or the caller is not an active member }
 *       429: { description: Per-organization or per-email invite limit reached }
 *       503: { description: Rate limiter unavailable }
 *   get:
 *     summary: List the organization's pending invitations
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     parameters:
 *       - { in: path, name: id, required: true, schema: { type: string, format: uuid } }
 *     responses:
 *       200: { description: Pending (unaccepted, unrevoked, unexpired) invitations }
 *       403: { description: Caller is a member but not an owner or admin }
 *       404: { description: Organization not found, or the caller is not an active member }
 */
organizationRouter.post(
    '/:id/invitations',
    validateRequest({ params: orgParamsSchema, body: createInvitationSchema }),
    CreateInvitation,
);
organizationRouter.get(
    '/:id/invitations',
    validateRequest({ params: orgParamsSchema }),
    ListInvitations,
);

/**
 * @swagger
 * /api/v1/organizations/{id}/audit-events:
 *   get:
 *     summary: List the organization's audit events, newest first
 *     description: >
 *       Behind ORGS_ENABLED. Owner or admin only (a developer or viewer gets 403, a
 *       non-member the same 404 as a missing org). Cursor-paginated: pass the previous
 *       response's `next_cursor` as `cursor`; null means the end. Each event has the action,
 *       time, old and new role, and the actor and target accounts (display name, plus email
 *       for managers). Never contains an invitation token, hash or invited email. Limited
 *       to 60 requests per minute per (organization, account); refused with 503 if the
 *       limiter is unavailable.
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     parameters:
 *       - { in: path, name: id, required: true, schema: { type: string, format: uuid } }
 *       - { in: query, name: limit, schema: { type: integer, minimum: 1, maximum: 100, default: 50 } }
 *       - { in: query, name: cursor, schema: { type: string, maxLength: 100 } }
 *       - { in: query, name: actor_account_id, schema: { type: string, format: uuid } }
 *       - { in: query, name: target_account_id, schema: { type: string, format: uuid } }
 *       - { in: query, name: action, schema: { type: string } }
 *       - { in: query, name: from, schema: { type: string, format: date-time, description: "UTC, ending in Z" } }
 *       - { in: query, name: to, schema: { type: string, format: date-time, description: "UTC, ending in Z" } }
 *     responses:
 *       200: { description: "{ events: [{ id, action, occurred_at, actor, target, old_role, new_role }], next_cursor }" }
 *       403: { description: Caller is a member but not an owner or admin }
 *       404: { description: Organization not found, or the caller is not an active member }
 *       422: { description: Unknown query key, bad uuid, action, cursor or time, or from after to }
 *       429: { description: Read limit reached }
 *       503: { description: Rate limiter unavailable }
 */
organizationRouter.get(
    '/:id/audit-events',
    validateRequest({ params: orgParamsSchema, query: auditQuerySchema }),
    ListAuditEvents,
);

/**
 * @swagger
 * /api/v1/organizations/{id}/invitations/{invitationId}:
 *   delete:
 *     summary: Revoke a pending invitation
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     parameters:
 *       - { in: path, name: id, required: true, schema: { type: string, format: uuid } }
 *       - { in: path, name: invitationId, required: true, schema: { type: string, format: uuid } }
 *     responses:
 *       204: { description: Revoked }
 *       403: { description: Caller is a member but not an owner or admin }
 *       404: { description: Not found, already used, or belongs to another organization }
 */
organizationRouter.delete(
    '/:id/invitations/:invitationId',
    validateRequest({ params: orgInvitationParamsSchema }),
    RevokeInvitation,
);

/**
 * @swagger
 * /api/v1/organizations/{id}/transfer-ownership:
 *   post:
 *     summary: Transfer the organization to another active member
 *     description: >
 *       Behind ORGS_ENABLED. Only the current owner (resolved from the token's account and
 *       an ACTIVE owner Membership, never the request) may call this, and the token's
 *       auth_time must be within the exit flow's reauth window (401 reauth_required
 *       otherwise). In one transaction the target becomes owner and the caller becomes
 *       admin; the caller's refresh tokens are revoked, so they must sign in again. A
 *       personal organization cannot be transferred.
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     parameters:
 *       - { in: path, name: id, required: true, schema: { type: string, format: uuid } }
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required: [new_owner_account_id]
 *             properties:
 *               new_owner_account_id: { type: string, format: uuid }
 *     responses:
 *       200: { description: Ownership transferred }
 *       401: { description: Stale or missing auth_time (code reauth_required) }
 *       403: { description: Caller is a member but not the owner }
 *       404: { description: Organization not found, or the caller is not an active member }
 *       409: { description: Target is not an eligible member, is the caller, or the org is personal }
 */
organizationRouter.post(
    '/:id/transfer-ownership',
    validateRequest({ params: orgParamsSchema, body: transferOwnershipSchema }),
    TransferOwnership,
);

/**
 * @swagger
 * /api/v1/invitations/accept:
 *   post:
 *     summary: Accept an organization invitation
 *     description: >
 *       Behind ORGS_ENABLED. Requires a session bearer token (Authorization header, so it
 *       is not CSRF-able) AND the invitation token in the body (never the URL). The
 *       session's credential must be email-verified and its email must equal the invited
 *       email. Every rejection reason returns the same 400.
 *     tags: [Organizations]
 *     security: [{ bearerAuth: [] }]
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required: [token]
 *             properties:
 *               token: { type: string }
 *     responses:
 *       200: { description: Membership created or revived }
 *       400: { description: Invitation invalid, expired, used, revoked, or for another account }
 *       409: { description: Already a member, or the account could not be linked }
 */
invitationRouter.post(
    '/accept',
    validateRequest({ body: acceptInvitationSchema }),
    AcceptInvitation,
);
