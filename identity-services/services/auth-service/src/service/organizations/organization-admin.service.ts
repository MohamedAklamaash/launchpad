import { HttpError, sanitizeDisplayName } from '@launchpad/common';
import { Op } from 'sequelize';
import { Membership, Organization } from '@/db';
import { sequelize } from '@/db/sequalize';
import { ORG_ROLE, type OrgRole } from '@/types/org-role';
import type { AccessTokenPayload } from '@/utils/handle-token';
import { otpAttempts } from '@/utils/otp-attempts';
import { recordAuditEvent } from './audit-log.service';
import { requireOrgManager, requireVerifiedCaller } from './org-access.service';
import { hasVerifiedCredential, personalOrgIdsAmong } from './org-identity';
import { lockManagerActor } from './actor-lock';
import { enforceOrgActionSlot, enforceSlot } from './org-rate-limit';
import { createOrganization } from './organization.service';

export interface OrganizationSummary {
    id: string;
    name: string;
    role: OrgRole;
    is_personal: boolean;
}

// Counts every org the account owns, personal included.
export const MAX_OWNED_ORGS = 20;

const cleanName = (raw: string): string => {
    const name = sanitizeDisplayName(raw);
    if (!name) throw new HttpError(422, 'Name must contain at least one letter or digit');
    return name;
};

// Only the caller's own ACTIVE memberships, resolved from the verified credential's
// account. The org id never comes from the request.
export const listMyOrganizations = async (
    caller: AccessTokenPayload,
): Promise<OrganizationSummary[]> => {
    const { accountId } = await requireVerifiedCaller(caller);
    const memberships = await Membership.findAll({
        where: { account_id: accountId, removed_at: null },
        order: [['created_at', 'ASC']],
    });
    if (memberships.length === 0) return [];

    const organizations = await Organization.findAll({
        where: { id: { [Op.in]: memberships.map((m) => m.organization_id) } },
    });
    const personalIds = await personalOrgIdsAmong(organizations);
    const byId = new Map(organizations.map((org) => [org.id, org]));

    return memberships.flatMap((membership) => {
        const org = byId.get(membership.organization_id);
        if (!org) return [];
        return [
            {
                id: org.id,
                name: org.name,
                role: membership.role,
                is_personal: personalIds.has(org.id),
            },
        ];
    });
};

// The id is generated by Organization's own default (a fresh uuidv7, never a uuid5), so it
// is server-chosen and can never equal a personal-org id. Nothing in this path accepts an
// id from the request.
//
// Order: verified, unshared Account first (nothing is spent for an unverified caller), then
// the name, then the per-Account limiter, then the write.
export const createTeamOrganization = async (
    caller: AccessTokenPayload,
    rawName: string,
): Promise<OrganizationSummary> => {
    const owner = await requireVerifiedCaller(caller);
    if (!(await hasVerifiedCredential(owner.accountId))) {
        throw new HttpError(403, 'A verified account with a single sign-in is required');
    }
    const name = cleanName(rawName);
    const owned = await Membership.count({
        where: { account_id: owner.accountId, role: ORG_ROLE.OWNER, removed_at: null },
    });
    if (owned >= MAX_OWNED_ORGS) {
        throw new HttpError(409, `An account can own at most ${MAX_OWNED_ORGS} organizations`);
    }
    await enforceSlot(() => otpAttempts.consumeOrgCreateSlot(owner.accountId), {
        tooMany: 'Too many organizations created recently - try again later',
        unavailable: 'Organization creation is temporarily unavailable - try again shortly',
    });

    const { organization } = await createOrganization({
        ownerAccountId: owner.accountId,
        name,
        actorAccountId: owner.accountId,
    });
    return {
        id: organization.id,
        name: organization.name,
        role: ORG_ROLE.OWNER,
        is_personal: false,
    };
};

// Personal organizations may be renamed: the name is cosmetic and nothing keys on it (the
// id is derived from the user id, never the name), and login never rewrites an existing org.
export const renameOrganization = async (
    caller: AccessTokenPayload,
    organizationId: string,
    rawName: string,
): Promise<{ id: string; name: string }> => {
    const manager = await requireOrgManager(caller, organizationId);
    const name = cleanName(rawName);
    await enforceOrgActionSlot(organizationId, manager.accountId);

    await sequelize.transaction(async (transaction) => {
        await lockManagerActor(organizationId, manager.accountId, transaction);
        const [updated] = await Organization.update(
            { name },
            { where: { id: organizationId }, transaction },
        );
        if (updated === 0) throw new HttpError(404, 'Organization not found');
        await recordAuditEvent(transaction, {
            organization_id: organizationId,
            actor_account_id: manager.accountId,
            action: 'organization.renamed',
            target_account_id: null,
            old_role: null,
            new_role: null,
        });
    });
    return { id: organizationId, name };
};
